// Bakes the par (fewest pushes, from the solver) of every official level into src/game/pars.ts, so neither the client
// nor the server ever runs the solver at play time (a hard level takes ~300 ms to solve, far more on a phone).
//   node tools/run.mjs tools/pars.ts           print the table and compare it with the committed one (exit 1 if stale)
//   node tools/run.mjs tools/pars.ts --write   regenerate src/game/pars.ts
// Run it with --write whenever LEVELS changes; tools/check.ts fails while the table is out of date.

import { writeFileSync } from 'node:fs'
import { LEVELS } from '../src/game/levels'
import { LEVEL_PARS } from '../src/game/pars'
import { solve } from '../src/game/solver'

declare const process: { argv: string[]; exitCode?: number }

const pars = LEVELS.map((level, i) => {
  const s = solve(level)
  if (!s.solvable) throw new Error(`level ${i + 1} (${level.name}) has no solution`)
  return s.pushes
})
console.log(pars.map((p, i) => `${i + 1}: ${p}`).join('\n'))

if (process.argv.includes('--write')) {
  const body = `// Generated by tools/pars.ts from the solver: fewest pushes for each official level, in LEVELS order. Do not edit;
// run \`node tools/run.mjs tools/pars.ts --write\` after changing LEVELS.
export const LEVEL_PARS: readonly number[] = [${pars.join(', ')}]
`
  writeFileSync('src/game/pars.ts', body)
  console.log('wrote src/game/pars.ts')
} else if (pars.length !== LEVEL_PARS.length || pars.some((p, i) => p !== LEVEL_PARS[i])) {
  console.log('src/game/pars.ts is out of date: run with --write')
  process.exitCode = 1
}
